using SegoLib.DataProviders;
using SegoLib.Random;
using System.Collections.Generic;
using UnityEngine;

namespace SegoLib.Distributions
{
    public partial class Distribution : IRandomDataProvider<float>
    {
        /// <summary>
        /// The normalized distribution data this Distribution will use for number generation.
        /// </summary>
        private IReadOnlyList<DistributionData> m_distData;

        /// <summary>
        /// The range between which this distribution will generate numbers.
        /// </summary>
        public FloatRange Scale => m_scale;
        private FloatRange m_scale;

        /// <summary>
        /// Ctor.
        /// </summary>
        /// <param name="distributionData">The distribution curve used to generate numbers.</param>
        /// <param name="min">The minimum value generated by this distribution.</param>
        /// <param name="max">The maximum value generated by this distribution.</param>
        public Distribution(IReadOnlyList<DistributionData> distributionData, float min = 0, float max = 1)
        {
            // Populate with dummy data if data is null or empty.
            if(distributionData == null || distributionData.Count == 0) {
                m_distData = PrecalculatedDistributions.Uniform;
                return;
            } else {
                m_distData = distributionData;
            }

            m_scale = new FloatRange(min, max);
        }

        /// <summary>
        /// Get the prevalence of <paramref name="value"/> in this distribution.<br/>
        /// Prevalence is how likely a given value is to occur versus the highest weighted value of this distribution.<br/>
        /// ex. A weight of 0.3 against a highest weight of 0.5 results in a prevalence of 0.6.
        /// </summary>
        /// <param name="value"></param>
        /// <returns></returns>
        public float GetProbabilityMass(float value)
        {
            float scaledValue = m_scale.InverseLerp(value);

            int index = DistributionUtilities.FindBestIndexOfValue(m_distData, scaledValue);

            if(index == 0)
                return m_distData[0].probabilityMass;

            float t = Mathf.InverseLerp(m_distData[index-1].value, m_distData[index].value, scaledValue);

            return Mathf.Lerp(m_distData[index - 1].probabilityMass, m_distData[index].probabilityMass, t);
        }

        /// <summary>
        /// Get a random value weighted on this distribution.
        /// </summary>
        /// <returns></returns>
        public float GetValue()
        {
            float r = UnityEngine.Random.value;

            int index = DistributionUtilities.FindBestIndexOfCumulativeDensity(m_distData, r);

            if(index == 0)
                return m_distData[0].value;

            float t = Mathf.InverseLerp(m_distData[index - 1].cumulativeDensity, m_distData[index].cumulativeDensity, r);
            return m_scale.Lerp(Mathf.Lerp(m_distData[index - 1].value, m_distData[index].value, t));
        }
    }
}
